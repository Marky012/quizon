/* ===========================================================================
   MEDIUM TIER - EXPANSION (M037 - M121)

   Added 2026-10-04. 14 items per story, bringing all six Medium pools to 20.

   WHAT "MEDIUM" MEANS HERE, and why it is not just "more questions":

   - The answer is never stated in one sentence. A learner must hold two lines
     at once, or read one line and work out what it IMPLIES. Easy can be
     answered by pointing; Medium cannot.
   - Questions ask WHY a sentence is there, not WHAT it says. "Why does the
     text say so far?" is Medium. "How many casualties?" is Easy.
   - Distractors are tempting because they are true-ish. They are drawn from
     the passage itself, or from the right shape with the wrong content, so a
     learner who skims still gets punished.

   The trap to avoid: making Medium harder by making the WORDS harder. That
   just tests vocabulary and punishes a nine-year-old who knows the idea but not
   the word. Every distractor below is built to be defeated by reasoning about
   the passage, not by knowing a longer word.
   =========================================================================== */

